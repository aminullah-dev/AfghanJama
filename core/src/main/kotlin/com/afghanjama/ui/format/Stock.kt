package com.afghanjama.ui.format

/**
 * وضعیتِ یک ردیفِ انبار به زبانِ کارگاه.
 *
 * تعدادِ منفی «منفی ۲۱ عدد» نیست — «کسری ۲۱ عدد» است، یعنی به اندازهٔ ۲۱
 * عدد جنس فروخته‌ایم که هنوز واردش نکرده‌ایم. نوشتنِ عددِ منفی روی صفحه
 * کسی را در کارگاه راهنمایی نمی‌کند.
 */
fun stockText(qty: Int): String = when {
    qty > 0 -> "موجودیِ انبار: ${qty.fa()} عدد"
    qty < 0 -> "کسری: ${(-qty).fa()} عدد"
    else -> "موجودیِ انبار: صفر"
}

/** برچسبِ کوتاه برای فهرست‌ها. */
fun stockBadge(qty: Int): String = when {
    qty > 0 -> "موجودی: ${qty.fa()}"
    qty < 0 -> "کسری: ${(-qty).fa()}"
    else -> "موجودی: ۰"
}

/** ردیفی که کسری دارد باید قرمز دیده شود. */
fun isShortage(qty: Int): Boolean = qty < 0

/**
 * نامِ خالیِ کارگر از برچسبِ کارگاه: «[T10] احمد» → «احمد».
 *
 * برچسب برای کارمزد و تحویلِ دوخت **کلیدِ درست** است
 * (`sewing_assignments.tailorLabel`)، ولی حضور و غیاب با نامِ خالی کار
 * می‌کند. تا پیش از این، ورودِ تأییدشده از وای‌فای برچسب را عیناً ذخیره
 * می‌کرد و آن سطر با هیچ کارگری تطبیق نمی‌خورد: کارگر «داخل» نمی‌شد،
 * خروجش بازه‌ای برای بستن پیدا نمی‌کرد، و ساعتش زیرِ یک نامِ دومِ خیالی
 * جمع می‌شد.
 *
 * نامی که براکت ندارد، یا براکتش ناقص است، دست‌نخورده برمی‌گردد — پس
 * صداکردنش روی نامِ خالی هم بی‌خطر است.
 */
fun String.bareWorkerName(): String {
    val t = trim()
    if (!t.startsWith("[")) return t
    val close = t.indexOf(']')
    if (close < 0) return t
    val rest = t.substring(close + 1).trim()
    // «[T10]» تنها، بی نام: چیزی برای برداشتن نیست، وگرنه خالی برمی‌گشت
    return rest.ifEmpty { t }
}
