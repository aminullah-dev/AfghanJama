package com.afghanjama.pdf

/**
 * متر — اندازهٔ متن پیش از کشیدنش.
 *
 * **چرا این لازم شد:** چیدمانِ سندهای این اپ روی ارتفاعِ متن سوار است.
 * هر سطر می‌گوید `y = kv(...)` و `kv` ارتفاعی را برمی‌گرداند که
 * `StaticLayout` پس از شکستنِ متن در عرضِ ستون حساب کرده. یعنی
 * نمی‌شود چیدمان را مشترک کرد و کشیدن را سکو-به-سکو گذاشت: خودِ
 * **موقعیت‌ها** به اندازه‌گیری وابسته‌اند.
 *
 * پس مرز یک پله عقب‌تر کشیده می‌شود. لایهٔ مشترک می‌پرسد «این متن با
 * این قلم و این عرض چقدر جا می‌گیرد؟» و هر سکو با ابزارِ خودش جواب
 * می‌دهد — اندروید با `StaticLayout`، ویندوز با `LineBreakMeasurer`.
 * بعد چیدمان روی همان جواب‌ها ساخته می‌شود و نتیجه یک [Sheet] است که
 * هر دو سکو یکسان می‌کشند.
 *
 * دو سکو هیچ‌وقت پیکسل‌به‌پیکسل یکی نمی‌شوند — قلم‌ها کمی فرق دارند —
 * ولی **قاعدهٔ چیدمان** یکی می‌ماند، و همان چیزی است که نباید دو تا شود.
 */
interface TextMeasurer {

    /** پهنای یک خطِ متن، بی شکستن. */
    fun width(text: String, size: Float, weight: Weight = Weight.Regular): Float

    /**
     * شکستنِ متن در عرضِ [maxWidth].
     *
     * اگر متن جا شود، فهرستی یک‌عضوی برمی‌گردد. متنِ خالی فهرستِ خالی
     * می‌دهد نه یک خطِ خالی، وگرنه سطرهای بی‌محتوا فضا می‌گیرند.
     */
    fun wrap(text: String, size: Float, maxWidth: Float, weight: Weight = Weight.Regular): List<String>

    /**
     * فاصلهٔ دو خطِ پشتِ هم برای این اندازه قلم.
     *
     * از خودِ قلم می‌آید نه ضریبِ حدسی، وگرنه روی یک سکو سطرها به هم
     * می‌چسبند و روی آن یکی از هم باز می‌شوند.
     */
    fun lineHeight(size: Float, weight: Weight = Weight.Regular): Float

    /** ارتفاعِ کلِ متن پس از شکستن — همان عددی که چیدمان با آن جلو می‌رود. */
    fun height(text: String, size: Float, maxWidth: Float, weight: Weight = Weight.Regular): Float =
        wrap(text, size, maxWidth, weight).size * lineHeight(size, weight)
}
