package com.afghanjama.lan

import com.afghanjama.ui.format.toLatinDigits

/**
 * پاک‌سازی و وارسیِ نشانیِ گوشیِ اصلی، پیش از آنکه به شبکه داده شود.
 *
 * **چرا لازم شد — یک گزارشِ واقعی از کارگاه:**
 *
 * کاربر `10.0.0101` را وارد کرده بود؛ یک نقطه کم. اپ بی هیچ ایرادی
 * قبولش کرد، وصل نشد، و پیام داد «مطمئن شوید هر دو گوشی روی وای‌فای
 * کارگاه‌اند». کاربر رفت سراغِ وای‌فای، هات‌اسپات و گوشیِ دیگر — در حالی
 * که هیچ‌کدام خراب نبودند.
 *
 * بدتر اینکه این نشانی روی دو سکو **دو رفتار** دارد: جاوای رومیزی شکلِ
 * سه‌بخشیِ قدیمی را می‌بخشد و `10.0.0101` را `10.0.0.101` می‌خواند،
 * ولی اندروید نمی‌بخشد و آن را «نامِ میزبان» می‌گیرد و دنبالِ DNS
 * می‌گردد. یعنی همان تایپ روی ویندوز کار می‌کرد و روی گوشی نه.
 *
 * **و یک تلهٔ ساختهٔ خودمان:** گوشیِ اصلی نشانی را با **رقمِ فارسی**
 * نشان می‌دهد (`۱۰.۰.۰.۱۰۱`) ولی کادرِ ورودی هیچ تبدیلی نداشت. هر
 * کاربری که همان چیزی را که می‌بیند تایپ کند، نشانیِ نامعتبر می‌سازد.
 *
 * پس اینجا سه کار می‌شود: ارقام لاتین می‌شوند، چیزهای اضافه برداشته
 * می‌شوند، و اگر باز هم درست نبود **دقیقاً گفته می‌شود کجا ایراد
 * دارد** — نه اینکه گردنِ شبکه بیفتد.
 */
object HostAddress {

    /** نتیجهٔ وارسی: یا نشانیِ تمیز، یا دلیلِ روشنِ رد شدن. */
    sealed interface Result {
        data class Ok(val host: String) : Result
        data class Bad(val reason: String) : Result
    }

    /**
     * پاک‌سازیِ ورودی بی آنکه چیزی رد شود — برای همان لحظهٔ تایپ.
     *
     * فقط ارقام را لاتین و فاصله‌ها را حذف می‌کند. **عمداً وارسی
     * نمی‌کند**، چون نشانیِ نیمه‌تایپ‌شده هنوز نامعتبر است و قرمز کردنِ
     * کادر سرِ حرفِ اول آزاردهنده است.
     */
    fun clean(raw: String): String =
        raw.toLatinDigits()
            .trim()
            .removePrefix("http://")
            .removePrefix("https://")
            .trimEnd('/')
            .filterNot { it.isWhitespace() }

    /** آیا این نشانی قابلِ استفاده است؟ اگر نه، چرا. */
    fun check(raw: String): Result {
        val s = clean(raw)
        if (s.isEmpty()) return Result.Bad("نشانی را وارد کنید.")

        // پورت را خودمان می‌گذاریم؛ اگر کاربر هم نوشته باشد، برمی‌داریم.
        val host = s.substringBefore(':')
        if (host.isEmpty()) return Result.Bad("نشانی را وارد کنید.")

        val parts = host.split('.')
        if (parts.size != 4) {
            return Result.Bad(
                "نشانی باید چهار بخش داشته باشد که با نقطه جدا شده‌اند، " +
                    "مثلِ ۱۰.۰.۰.۱۰۱ — این یکی ${parts.size.toString().toFa()} بخش دارد."
            )
        }
        for (p in parts) {
            if (p.isEmpty() || p.any { it !in '0'..'9' }) {
                return Result.Bad("هر بخشِ نشانی باید عدد باشد.")
            }
            // صفرِ ابتدایی عمداً رد می‌شود: بعضی کتابخانه‌ها آن را
            // **مبنای هشت** می‌خوانند، یعنی `0101` می‌شود ۶۵ و اپ بی‌صدا
            // به دستگاهِ دیگری وصل می‌شود. رد کردنش امن‌تر از حدس است.
            if (p.length > 1 && p[0] == '0') {
                return Result.Bad("بخشِ «$p» صفرِ اضافه دارد؛ بنویسید «${p.trimStart('0').ifEmpty { "0" }}».")
            }
            val n = p.toIntOrNull() ?: return Result.Bad("بخشِ «$p» عدد نیست.")
            if (n > 255) return Result.Bad("بخشِ «$p» از ۲۵۵ بیشتر است.")
        }
        return Result.Ok(host)
    }

    /** نشانیِ تمیز، یا `null` اگر معتبر نبود. */
    fun normalize(raw: String): String? = (check(raw) as? Result.Ok)?.host

    private fun String.toFa(): String =
        map { if (it in '0'..'9') "۰۱۲۳۴۵۶۷۸۹"[it - '0'] else it }.joinToString("")
}
