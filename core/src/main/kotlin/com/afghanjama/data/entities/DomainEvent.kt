package com.afghanjama.data.entities

import androidx.room.Entity
import androidx.room.Index
import androidx.room.PrimaryKey

/**
 * یک اتفاقِ **واقع‌شده** در دامنه — نه دستوری برای انجام دادن.
 *
 * **چرا جدول و نه گذرگاهِ درون‌حافظه‌ای.** گذرگاهِ حافظه‌ای دقیقاً همان
 * اشکالی را برمی‌گرداند که با مرزِ `Tx` بستیمش: نوشتن در دیتابیس و
 * خبر دادن به شنونده‌ها دو کارِ جدا می‌شوند، و اگر بینشان چیزی بیفتد
 * — کرش، بسته شدنِ اپ، مرگِ فرایند — یکی انجام شده و آن یکی نه. سرِ
 * پول یعنی سندی که ثبت شده ولی هیچ‌کس ندید.
 *
 * اینجا رویداد **در همان تراکنشی** نوشته می‌شود که دادهٔ اصلی نوشته
 * می‌شود. یا هر دو هستند یا هیچ‌کدام. این الگو نامِ خودش را دارد:
 * صندوقِ خروجیِ تراکنشی (transactional outbox).
 *
 * **[processedAt] چرا nullable است.** رویداد وقتی نوشته می‌شود هنوز
 * مصرف نشده. مصرف‌کننده (فعلاً بازتابِ حسابرسی، بعدها همگام‌سازی)
 * بعداً آن را مهر می‌زند. یعنی اگر اپ وسطِ پردازش بسته شود، رویداد
 * هنوز بی‌مهر است و دفعهٔ بعد دوباره برداشته می‌شود — هیچ‌چیز گم
 * نمی‌شود.
 *
 * **[payload] چرا رشته است و نه ستون‌های جدا.** شکلِ هر رویداد فرق
 * دارد و با هر نوعِ تازه ستونِ تازه یعنی مهاجرتِ تازه. یک رشتهٔ ساده
 * (`کلید=مقدار` جدا با `؛`) کافی است: این ستون برای **خواندنِ آدمی و
 * فرستادن** است، نه برای پرس‌وجوی تحلیلی. هر چیزی که باید فیلتر شود،
 * ستونِ خودش را دارد ([type]، [aggregate]، [aggregateId]).
 */
@Entity(
    tableName = "domain_events",
    indices = [
        Index(value = ["at"]),
        // مصرف‌کننده هر بار «هرچه هنوز مهر نخورده» را می‌پرسد؛ بی این
        // ایندکس، آن پرس‌وجو با بزرگ شدنِ جدول کلِ آن را می‌خواند.
        Index(value = ["processedAt"]),
        // «تاریخچهٔ این سفارش» — همان چیزی که صفحهٔ جزئیات می‌خواهد.
        Index(value = ["aggregate", "aggregateId"])
    ]
)
data class DomainEvent(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,

    /** چه اتفاقی افتاد — مثلاً «فروش ثبت شد». */
    val type: String,

    /** روی چه چیزی — «order»، «transaction»، «stock». */
    val aggregate: String,

    /** کدام یکی — کدِ سند یا شناسهٔ سطر. */
    val aggregateId: String,

    /** جزئیاتِ خواندنی. قالب: `کلید=مقدار؛کلید=مقدار` */
    val payload: String = "",

    /** چه کسی باعثش شد — همان نام و نقشی که حسابرسی ثبت می‌کند. */
    val user: String = "",
    val role: String = "",

    /** کِی افتاد. */
    val at: Long = System.currentTimeMillis(),

    /** کِی مصرف شد. `null` یعنی هنوز در نوبت است. */
    val processedAt: Long? = null
)
