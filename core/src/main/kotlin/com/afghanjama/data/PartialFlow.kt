package com.afghanjama.data

/**
 * جریانِ جزئیِ سفارش: هر عدد که دوخته شد جلو می‌رود، بی‌آنکه منتظرِ باقی بماند.
 *
 * صاحبِ کارگاه این را با نانوا توضیح داد: نانوا هر نان که پخت به صف
 * می‌دهد، در حالی که در تنور هنوز نانِ نیم‌پخته هست. سفارشِ ۳۰ عددی هم
 * بینِ چند خیاط پخش می‌شود و کم‌کم تمام می‌شود؛ خیاطی که ۱۰ عدد دارد
 * می‌تواند هر چند تا که دوخته تحویل دهد. **این جریانِ عادیِ کار است، نه
 * حالتِ استثنایی.**
 *
 * پس تعداد در هر مرحله **جاری** است، نه یک عددِ ثابتِ سفارش. سه عدد روی
 * سفارش نگه داشته می‌شود:
 *  - `reviewQty` چند عدد همین حالا دستِ نظارت است
 *  - `storedQty` چند عدد تا امروز وارد انبار محصول شده
 *  - `storedCost` چه مبلغی تا امروز از «کار در جریان» بیرون رفته
 *
 * ریاضیِ تقسیمِ بها اینجاست چون همین یک جا تصمیم می‌گیرد چقدر پول از
 * «کار در جریان» به «موجودی محصول» برود؛ اگر جمعِ ارسال‌های جزئی با کلِ
 * بهای سفارش نخوانَد، آن دو حساب برای همیشه از هم جدا می‌افتند.
 *
 * هیچ چیزِ اندرویدی و هیچ دیتابیسی اینجا نیست تا CI بسنجدش.
 */
object PartialFlow {

    /** یک تحویلِ دوخته‌شدهٔ خیاط: تعداد، کارمزدِ فی‌عدد، و لحظهٔ تحویل. */
    data class Sewn(val qty: Int, val unitWage: Long, val doneAt: Long)

    /**
     * چند عدد همین حالا می‌تواند به نظارت برود.
     *
     * [sewn] کلِ عددهای دوخته‌شدهٔ سفارش است، نه عددهای تازه. آنچه از قبل
     * دستِ نظارت است یا وارد انبار شده کم می‌شود، وگرنه هر بار زدنِ دکمه
     * همان عددها را دوباره می‌فرستد و انبار چند برابر پر می‌شود.
     *
     * سقفش هم باقی‌ماندهٔ خودِ سفارش است: دوختِ دوباره پس از برگشتِ نظارت
     * `sewn` را بالاتر از `qty` می‌برد، ولی سفارش بیش از عددِ خودش کالا
     * ندارد.
     */
    fun readyToSend(qty: Int, sewn: Int, inReview: Int, stored: Int): Int {
        val accounted = inReview + stored
        return minOf(sewn - accounted, qty - accounted).coerceAtLeast(0)
    }

    /**
     * دستمزدِ دوختِ [n] عددِ اولی که تحویل شده — به ترتیبِ تحویل.
     *
     * چرا به ترتیب و نه سرشکن: کارمزدِ هر خیاط فرق دارد. اگر دستمزدِ کلِ
     * سفارش سرشکن شود، عددهایی که خیاطِ گران دوخته با بهای خیاطِ ارزان
     * وارد انبار می‌شوند و بهای تمام‌شدهٔ هر دسته دروغ می‌شود.
     */
    /**
     * از هر تحویل چند عدد هنوز جلو نرفته.
     *
     * [qtys] تعدادِ هر تحویل به ترتیبِ زمانِ تکمیل و [alreadyGone] عددهایی
     * که از قبل دستِ نظارت‌اند یا در انبار. همان ترتیبِ FIFO که کارمزد هم
     * از آن پیروی می‌کند، پس صفحه و پول یک داستان می‌گویند.
     *
     * برمی‌گرداند: باقی‌ماندهٔ هر تحویل، در همان ترتیبِ ورودی. صفر یعنی
     * آن تحویل کاملاً جلو رفته و نباید در فهرستِ «آمادهٔ نظارت» دیده شود.
     */
    fun pendingPerBatch(qtys: List<Int>, alreadyGone: Int): List<Int> {
        var left = alreadyGone.coerceAtLeast(0)
        return qtys.map { q ->
            val eaten = minOf(left, q.coerceAtLeast(0))
            left -= eaten
            (q - eaten).coerceAtLeast(0)
        }
    }

    fun wageOfFirst(batches: List<Sewn>, n: Int): Long {
        if (n <= 0) return 0L
        var left = n
        var sum = 0L
        for (b in batches.sortedBy { it.doneAt }) {
            if (left <= 0) break
            val take = minOf(left, b.qty)
            sum += take * b.unitWage
            left -= take
        }
        return sum
    }

    /**
     * بهایی که با ورودِ [batch] عدد به انبار محصول باید از «کار در جریان»
     * بیرون برود.
     *
     * [fixedCost] بهای مشترکِ کلِ سفارش است (پارچه + خرج‌کار) و به نسبتِ
     * تعداد پخش می‌شود. [sewnCost] کلِ دستمزدِ ثبت‌شدهٔ سفارش است و فقط در
     * آخرین دسته به کار می‌آید؛ دسته‌های میانی دستمزدِ **همان عددها** را
     * می‌برند نه سهمِ سرشکن‌شده.
     *
     * حساب انباشته است، نه دسته‌به‌دسته: هر بار سهمِ کلِ عددهای رفته حساب
     * می‌شود و آنچه قبلاً رفته ([storedCost]) کم می‌شود. برای همین ته‌ماندهٔ
     * تقسیمِ صحیح گم نمی‌شود.
     *
     * آخرین دسته هرچه مانده را یک‌جا می‌برد. این تنها راهی است که
     * «کار در جریان» دقیقاً به صفر برگردد — هم ته‌ماندهٔ تقسیم را جمع
     * می‌کند، هم دستمزدِ دوختِ دوباره‌ای را که پس از برگشتِ نظارت ثبت شده.
     */
    fun depositValue(
        qty: Int,
        stored: Int,
        batch: Int,
        fixedCost: Long,
        sewnCost: Long,
        batches: List<Sewn>,
        storedCost: Long
    ): Long {
        if (qty <= 0 || batch <= 0) return 0L
        val cum = (stored + batch).coerceIn(0, qty)
        val target =
            if (cum >= qty) fixedCost + sewnCost
            else fixedCost * cum / qty + wageOfFirst(batches, cum)
        return (target - storedCost).coerceAtLeast(0L)
    }
}
