package com.afghanjama.util

/*
 * سه اولیهٔ رمزنگاری که [PinHash] لازم دارد — تنها چیزی که از سکو
 * می‌خواهد.
 *
 * **و چرا هیچ‌کدام روی iOS خالی نمی‌مانَد.** این‌ها قفلِ ورودِ کارگاه‌اند.
 * یک `TODO()` اینجا یعنی برنامه‌ای که یا باز نمی‌شود یا — بدتر — با هر
 * رمزی باز می‌شود.
 *
 * **نامِ الگوریتم عمداً همان رشتهٔ جاواست** (`PBKDF2WithHmacSHA256`).
 * دلیلش این است که آن نام **داخلِ خودِ رشتهٔ ذخیره‌شده** نوشته می‌شود، و
 * پشتیبانی که از گوشی گرفته می‌شود باید روی آیفون هم باز شود. اگر iOS
 * نامِ دیگری می‌نوشت، رمزِ ساخته‌شده روی یک سکو روی آن یکی خوانده
 * نمی‌شد. پس هر سکو همان نام را به تابعِ بومیِ خودش ترجمه می‌کند.
 */

/** [n] بایتِ تصادفیِ رمزنگارانه — نه `Random` معمولی. */
internal expect fun secureRandomBytes(n: Int): ByteArray

/**
 * PBKDF2. اگر [algo] روی این دستگاه نبود `null` — تا [PinHash] بتواند
 * الگوریتمِ بعدیِ فهرستش را بیازماید.
 */
internal expect fun pbkdf2(
    pin: String,
    salt: ByteArray,
    iterations: Int,
    keyBits: Int,
    algo: String,
): ByteArray?

/** فقط برای خواندنِ رمزهای قالبِ قدیمی. */
internal expect fun sha256(data: ByteArray): ByteArray
