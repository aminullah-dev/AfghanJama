package com.afghanjama.data

/**
 * نتیجهٔ ویرایش یا حذفِ یک مشتری یا کارمند.
 *
 * **چرا فقط «شد/نشد» نیست.** کارگاه با کارگاهِ نمونه شروع می‌کند و بعد
 * آدم‌ها را از آنِ خودش می‌کند؛ وقتی کاری انجام نمی‌شود، باید بداند چرا و
 * چه کند. تغییرِ نام سابقه را با خودش می‌برد (`Repo`)، ولی به نامی که
 * از قبل هست نمی‌رود ([NAME_TAKEN]) و کسی که سابقه دارد حذف نمی‌شود
 * ([HAS_HISTORY]) — مانده‌اش بی‌صاحب می‌ماند.
 */
enum class PersonEdit {
    DONE,

    /** نام خالی است. */
    BLANK,

    /** این نام را کسِ دیگری دارد. */
    NAME_TAKEN,

    /** در کار و حساب آمده؛ حذف بسته است (تغییرِ نام آزاد است). */
    HAS_HISTORY,

    /** دیگر نیست — شاید همین حالا جای دیگری حذف شد. */
    MISSING;

    /** پیامِ فارسی برای کاربر؛ [noun] «مشتری» یا «کارمند». برای [DONE] خالی. */
    fun message(noun: String): String = when (this) {
        DONE -> ""
        BLANK -> "نام نمی‌تواند خالی باشد."
        NAME_TAKEN -> "این نام را ${noun}ِ دیگری دارد، یا سابقه‌ای زیرِ همین نام هست. " +
            "دو حساب یکی نمی‌شوند؛ نامِ دیگری بدهید."
        HAS_HISTORY ->
            "این $noun در کار و حسابِ کارگاه سابقه دارد و حذف نمی‌شود — نامش را " +
                "می‌شود عوض کرد. اگر از کارگاهِ نمونه است، اول «پاک‌کردن کارها و حساب‌ها» " +
                "را در تنظیمات بزنید."
        MISSING -> "این $noun دیگر در فهرست نیست."
    }
}
