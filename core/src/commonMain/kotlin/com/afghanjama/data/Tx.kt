package com.afghanjama.data

/**
 * مرزِ تراکنش — **مرزِ هشتمِ سکو**، و مهم‌ترینشان.
 *
 * **اشکالی که این مرز می‌بندد:**
 *
 * یک فاکتورِ فروش حدودِ ده نوشتنِ مستقل انجام می‌دهد — کم کردنِ انبار،
 * ثبتِ نقد، دفترِ مشتری، سند، لاگِ حسابرسی، و دو ژورنال. تا امروز
 * هیچ‌کدام در تراکنش نبودند. اگر پروسه وسطِ این ده تا بمیرد — باتری،
 * کشته شدن به‌خاطرِ حافظه، یا کرش — **دفتر نیمه‌نوشته می‌مانَد**: انبار
 * کم شده ولی پول ثبت نشده، یا ژورنالِ نامتوازن.
 *
 * روی اندروید این فرضی نیست؛ سیستم هر لحظه می‌تواند پروسه را بکشد.
 *
 * **چرا مرز لازم بود و نمی‌شد مستقیم `withTransaction` صدا زد:**
 *
 * `Repo` در `:core` است و `:core` عمداً فقط `room-common` دارد —
 * حاشیه‌نویسی‌ها، نه موتور. یعنی ماژولی که تمامِ منطقِ پول را دارد
 * **حتی نمی‌تواند** تراکنش باز کند. تصمیمِ درستِ استقلالِ سکو (که نسخهٔ
 * ویندوز را ممکن کرد) ناخواسته اتمی بودن را برداشته بود.
 *
 * پس همان الگوی هفت مرزِ قبلی: `:core` فقط این واسط را می‌بیند، و هر
 * سکو پیاده‌سازیِ خودش را می‌دهد.
 *
 * **قاعده‌ای که باید نگه داشته شود:** هر کاری که بیش از یک جدول را
 * تغییر می‌دهد باید درونِ [atomic] باشد. مخصوصاً هر چیزی که هم‌زمان به
 * انبار و پول دست می‌زند.
 */
interface Tx {

    /**
     * [block] را طوری اجرا می‌کند که یا **همه‌اش** ماندگار شود یا
     * **هیچ‌کدام**.
     *
     * اگر [block] استثنا بدهد، همه‌چیز برمی‌گردد و استثنا بالا می‌رود.
     * بازگشتِ عادی یعنی commit.
     *
     * تودرتو بودن مجاز است: تراکنشِ درونی در بیرونی ادغام می‌شود، پس
     * فرمانی که فرمانِ دیگری را صدا می‌زند خودبه‌خود درست کار می‌کند.
     */
    suspend fun <T> atomic(block: suspend () -> T): T
}

/**
 * پیاده‌سازیِ بی‌اثر — **فقط برای آزمون‌های خالص**.
 *
 * عمداً `internal` نیست تا آزمون‌ها بتوانند از آن استفاده کنند، ولی
 * هیچ سکویی نباید این را به `Repo` بدهد. بررسیِ `txcheck` جلوی آن را
 * می‌گیرد.
 */
object NoTx : Tx {
    override suspend fun <T> atomic(block: suspend () -> T): T = block()
}
