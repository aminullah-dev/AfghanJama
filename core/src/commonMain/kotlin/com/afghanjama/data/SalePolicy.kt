package com.afghanjama.data

import kotlin.concurrent.Volatile

/**
 * سیاستِ فروش: آیا فروشِ بیشتر از موجودیِ ثبت‌شده («کسری») مجاز است؟
 *
 * در کارگاهِ واقعی جنس گاهی پیش از آنکه کسی ورودش را ثبت کند فروخته
 * می‌شود. اگر اپ جلویش را بگیرد، فروشنده مجبور می‌شود یک ورودیِ الکی
 * بزند و همان دروغ برای همیشه در حساب می‌ماند. پس اجازه داده می‌شود،
 * ولی کسری با رنگِ قرمز دیده می‌شود.
 *
 * **چرا اینجا و نه در `prefs`:** خودِ تصمیم یک بولین است و هیچ ربطی به
 * SharedPreferences ندارد؛ فقط ذخیره‌اش سکو-به-سکو فرق می‌کند. تا
 * دیروز این دو به هم چسبیده بودند و `Repo` را — که هیچ چیزِ اندرویدی
 * نداشت — به اندروید گره می‌زدند.
 *
 * هر سکو مقدارِ ذخیره‌شده را با [set] اینجا می‌گذارد و منطق فقط
 * [allowNegativeStock] را می‌خواند.
 */
object SalePolicy {

    @Volatile
    private var allow: Boolean = DEFAULT_ALLOW

    /** پیش‌فرض: اجازه هست. */
    const val DEFAULT_ALLOW = true

    /**
     * تا وقتی سکو مقدارِ ذخیره‌شده را نگذاشته، پیش‌فرض برمی‌گردد — که
     * همان تنظیمِ پیش‌فرض هم هست، پس اختلافی پیش نمی‌آید.
     */
    fun allowNegativeStock(): Boolean = allow

    fun set(value: Boolean) {
        allow = value
    }
}
