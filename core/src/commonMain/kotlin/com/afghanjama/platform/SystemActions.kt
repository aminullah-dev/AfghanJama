package com.afghanjama.platform

import androidx.compose.runtime.staticCompositionLocalOf

/**
 * کارهایی که اپ از **سیستم‌عامل** می‌خواهد، نه از خودش.
 *
 * مرزِ دومِ فازِ ۴.۵. بعد از [com.afghanjama.prefs.Settings]، چیزی که
 * بیشترین صفحه را در `:app` نگه داشته بود همین دوتا بود: «این متن را با
 * یک اپِ دیگر به‌اشتراک بگذار» و «این شماره را بگیر». هر دو در پنج
 * صفحه با کدِ یکسان تکرار شده بودند.
 *
 * عمداً کوچک است. هر چیزی که سکو بتواند انجام دهد اینجا نمی‌آید — فقط
 * آنچه صفحه‌های مشترک واقعاً صدا می‌زنند. واسطی که همه‌چیز را بپوشاند،
 * روی سکویی که نصفش را ندارد به دروغ تبدیل می‌شود.
 */
interface SystemActions {

    /**
     * متن را به اپ‌های دیگر می‌دهد (واتس‌اپ، ایمیل، …).
     *
     * [title] عنوانِ پنجرهٔ انتخاب است — روی اندروید همان
     * `Intent.createChooser`.
     */
    fun shareText(title: String, text: String)

    /**
     * شماره را برای تماس آماده می‌کند.
     *
     * **رفتارش روی دو سکو یکی نیست و این پنهان نمی‌شود:** روی گوشی
     * برنامهٔ تماس با شماره باز می‌شود. پی‌سیِ کارگاه تلفن ندارد، پس
     * آنجا شماره در کلیپ‌بورد کپی می‌شود تا کاربر بتواند جایی بچسبانَدش.
     *
     * کارِ دیگری هم می‌شد کرد — مثلاً دکمه را روی ویندوز نشان ندهیم —
     * ولی آن‌وقت دو صفحهٔ متفاوت می‌داشتیم و همین کار را بی‌فایده می‌کرد.
     */
    fun dial(phone: String)
}

/**
 * راهِ رسیدنِ صفحه‌ها به این کارها.
 *
 * مثلِ `LocalSettings` پیش‌فرض ندارد و بلند می‌شکند: پیاده‌سازیِ ساختگی
 * یعنی کاربر دکمهٔ «اشتراک» را بزند و هیچ اتفاقی نیفتد، و هیچ‌کس هم
 * نفهمد چرا.
 */
val LocalSystemActions = staticCompositionLocalOf<SystemActions> {
    error(
        "LocalSystemActions داده نشده. ریشهٔ هر سکو باید با " +
            "CompositionLocalProvider(LocalSystemActions provides …) پیچیده شود."
    )
}
