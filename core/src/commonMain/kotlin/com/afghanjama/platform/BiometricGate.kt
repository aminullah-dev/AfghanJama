package com.afghanjama.platform

import androidx.compose.runtime.staticCompositionLocalOf

/**
 * تأییدِ هویت پیش از ثبتِ ورود و خروج.
 *
 * **چرا لازم است.** حضور و غیاب تنها جایی است که یک کارمند می‌تواند
 * به نامِ کارمندِ دیگری چیزی ثبت کند. اثرِ انگشت این را می‌بندد.
 *
 * **و چرا `null` جوابِ درستی است.** پی‌سیِ کارگاه حسگرِ اثرِ انگشت
 * ندارد. اینجا `null` یعنی «این سکو نمی‌تواند بسنجد» و صفحه بی آن
 * کارش را می‌کند — دقیقاً همان کاری که نسخهٔ اندرویدی هم روی گوشیِ
 * بی‌حسگر می‌کرد (`isAvailable` که `false` بود، `onSuccess` را
 * مستقیم صدا می‌زد).
 *
 * تفاوتش با نبودنِ واسط این است که حالا **نوشته شده** کدام سکو چه
 * چیزی را نمی‌سنجد، به‌جای اینکه کلِ صفحه از یک سکو غایب باشد.
 */
interface BiometricGate {
    /**
     * [onSuccess] فقط پس از تأییدِ کاربر صدا زده می‌شود.
     *
     * اگر حسگر روی دستگاه نباشد، پیاده‌سازی باید [onSuccess] را
     * مستقیم صدا بزند — نه اینکه کار را ببندد. بستنِ کار روی دستگاهی
     * که حسگر ندارد یعنی کارگاه نمی‌تواند حضور ثبت کند.
     */
    fun confirm(
        title: String,
        subtitle: String,
        onSuccess: () -> Unit,
        onError: (String) -> Unit = {},
    )
}

/** `null` یعنی این سکو راهی برای سنجشِ هویت ندارد. */
val LocalBiometricGate = staticCompositionLocalOf<BiometricGate?> { null }
