package com.afghanjama.lan

import com.afghanjama.data.Db

/**
 * «این دستگاه در شبکهٔ کارگاه چیست؟»
 *
 * سه چیزی که `WorkshopLinkViewModel` از سکو می‌خواهد و هیچ‌کدام را
 * `:core` نمی‌داند. تا امروز هر سه مستقیم در خودِ ViewModel صدا زده
 * می‌شدند (`androidLocalIp`, `buildAppDatabase`, `Build.MODEL`) و همان
 * سه خط بود که صفحهٔ «اشتراکِ کارگاه» را در `:app` نگه می‌داشت.
 *
 * این مرز روی ویندوز **معنیِ بیشتری** دارد تا روی گوشی: طبقِ تصمیمِ
 * کارفرما پی‌سی دفترِ حساب است و گوشی‌ها به آن وصل می‌شوند، پس
 * سرویس‌دهنده در عمل همین‌جاست.
 */
interface LanHost {

    /**
     * نامی که این دستگاه خودش را با آن معرفی می‌کند، تا وقتی کاربر
     * نامِ دلخواه ننوشته — روی گوشی مدلِ دستگاه، روی پی‌سی نامِ کامپیوتر.
     */
    val deviceName: String

    /**
     * نشانیِ این دستگاه در شبکهٔ محلی، یا `null` اگر پیدا نشد.
     *
     * روی اندروید از Wi-Fi پرسیده می‌شود چون در گوشی چند رابطِ شبکه
     * هست و حدسِ عمومی گاهی نشانیِ داده تلفن‌همراه را می‌دهد — که
     * گوشیِ خیاط از آن به دفتر نمی‌رسد.
     */
    fun localIp(): String?

    /**
     * همهٔ نشانی‌هایی که شاید گوشیِ کارگر از آن‌ها برسد، بهترین اول.
     *
     * وقتی دستگاه دو شبکه دارد (وای‌فای و سیم، یا وای‌فای و VPN) حدسِ
     * [localIp] ممکن است اشتباه باشد؛ صفحه بقیه را هم نشان می‌دهد تا
     * کارفرما مجبور نباشد نشانی را از تنظیماتِ سیستم پیدا کند.
     */
    fun localIps(): List<String> = listOfNotNull(localIp())

    /**
     * شبکه‌هایی که این دستگاه همین حالا رویشان است، به‌ازای هر نشانی —
     * برای اینکه [LanHub] بداند هنوز در کارگاه است یا نه.
     *
     * پیش‌فرض فقط زیرشبکه را دارد. سکویی که دروازه (مودم) را می‌شناسد آن
     * را هم اضافه می‌کند: گوشی از وای‌فای، کامپیوتر از جدولِ مسیریابی و ARP.
     * ممکن است کند باشد (کامپیوتر یک دستورِ سیستم اجرا می‌کند)؛ روی رشتهٔ
     * صفحه صدا زده نمی‌شود.
     */
    fun networks(): Map<String, LanNetwork> = Lan.links().associate { it.address to it.network }

    /**
     * دفترِ کارگاه، برای سرویس‌دهی به دستگاه‌های دیگر.
     *
     * تنبل است و فقط وقتی صدا زده می‌شود که کاربر واقعاً اشتراک را
     * روشن کند: بازکردنِ دیتابیس هزینه دارد و اکثرِ دستگاه‌ها هرگز
     * سرویس‌دهنده نمی‌شوند.
     */
    fun ledger(): Db
}
