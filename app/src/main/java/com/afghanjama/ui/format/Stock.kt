package com.afghanjama.ui.format

/**
 * وضعیتِ یک ردیفِ انبار به زبانِ کارگاه.
 *
 * تعدادِ منفی «منفی ۲۱ عدد» نیست — «کسری ۲۱ عدد» است، یعنی به اندازهٔ ۲۱
 * عدد جنس فروخته‌ایم که هنوز واردش نکرده‌ایم. نوشتنِ عددِ منفی روی صفحه
 * کسی را در کارگاه راهنمایی نمی‌کند.
 */
fun stockText(qty: Int): String = when {
    qty > 0 -> "موجودیِ انبار: ${qty.fa()} عدد"
    qty < 0 -> "کسری: ${(-qty).fa()} عدد"
    else -> "موجودیِ انبار: صفر"
}

/** برچسبِ کوتاه برای فهرست‌ها. */
fun stockBadge(qty: Int): String = when {
    qty > 0 -> "موجودی: ${qty.fa()}"
    qty < 0 -> "کسری: ${(-qty).fa()}"
    else -> "موجودی: ۰"
}

/** ردیفی که کسری دارد باید قرمز دیده شود. */
fun isShortage(qty: Int): Boolean = qty < 0
