#!/usr/bin/env bash
#
# آزمونِ راه‌اندازیِ اپِ اندروید روی شبیه‌ساز.
#
# **چرا لازم شد:** تا امروز CI فقط ثابت می‌کرد APK *ساخته* می‌شود. همان
# شکافی که سرِ ویندوز دیدیم — بسته سبز بود و برنامه روی پی‌سی بالا
# نمی‌آمد — برای اندروید هم باز بود، و اپ روی گوشیِ واقعی سرِ باز شدن
# کرش کرد بی‌آنکه هیچ بررسی‌ای چیزی بگوید.
#
# **چرا یک بار باز کردن کافی نبود:** نسخهٔ اولِ همین اسکریپت سبز شد در
# حالی که اپ روی گوشیِ کارگاه می‌ترکید. علتش این بود که نصبِ تازه سرِ
# **صفحهٔ ورود** می‌ماند: نه دیتابیس باز می‌شد، نه داشبورد ساخته می‌شد،
# نه هیچ ViewModelی داده می‌خواند. یعنی آزمون فقط ثابت می‌کرد
# `MainActivity` بالا می‌آید.
#
# پس اینجا اپ چهار بار و در چهار حالتِ متفاوت باز می‌شود — با حالتِ
# ذخیره‌شدهٔ ورود که مستقیم روی دیسک نوشته می‌شود، تا از دروازهٔ ورود رد
# شویم بی‌آنکه به لمسِ صفحه تکیه کنیم (که روی شبیه‌ساز شکننده است).
set -uo pipefail

PKG="com.afghanjama"
PREFS="/data/data/$PKG/shared_prefs/auth_prefs.xml"
DB="/data/data/$PKG/databases/afghanjama.db"

echo "── نصبِ APK روی شبیه‌ساز"
./gradlew --no-daemon :app:installDebug || exit 1

# ───────────────────────────────────────────────────────────────────
# نوشتنِ حالتِ ورود مستقیم روی دیسکِ اپ.
#
# APKِ دیباگ `debuggable` است، پس `run-as` اجازه دارد داخلِ پوشهٔ خصوصیِ
# اپ بنویسد. فایل اول با `adb push` به `/data/local/tmp` می‌رود و بعد
# با `run-as` کپی می‌شود؛ فرستادنِ متن روی ورودیِ استانداردِ `adb shell`
# گاهی سرِ سطرها به هم می‌ریزد و این راه آن ابهام را ندارد.
#
# نام‌های کلید از `AuthViewModel` می‌آیند و باید با آن یکی بمانند؛ اگر
# روزی آنجا عوض شد، این آزمون سرِ همان فاز قرمز می‌شود — که درست است،
# چون معنایش این است که کاربرانِ فعلی هم سرِ به‌روزرسانی از اپ بیرون
# می‌افتند.
# ───────────────────────────────────────────────────────────────────
seed_auth() {
    local role="$1"

    # اول اپ را ببند. اگر پروسه زنده باشد، `SharedPreferences` نسخهٔ
    # درونِ حافظه‌اش را نگه داشته و می‌تواند روی چیزی که همین الان
    # نوشتیم بنویسد. پروسهٔ تازه فایل را از دیسک می‌خواند.
    adb shell am force-stop "$PKG" >/dev/null 2>&1

    cat > /tmp/auth_prefs.xml <<XML
<?xml version='1.0' encoding='utf-8' standalone='yes' ?>
<map>
    <string name="pin">1234</string>
    <boolean name="logged_in" value="true" />
    <string name="role">$role</string>
    <string name="user_name">CI</string>
</map>
XML
    adb push /tmp/auth_prefs.xml /data/local/tmp/auth_prefs.xml >/dev/null || return 1
    adb shell "run-as $PKG mkdir -p /data/data/$PKG/shared_prefs" || return 1
    adb shell "run-as $PKG sh -c 'cat /data/local/tmp/auth_prefs.xml > $PREFS'" || return 1

    # وارسی کن که واقعاً نوشته شد. اگر `run-as` بی‌صدا شکست بخورد (روی
    # بعضی ایمیج‌ها اجازه ندارد)، اپ به صفحهٔ ورود می‌افتد و آزمون
    # **سبز** می‌ماند در حالی که هیچ‌چیزِ تازه‌ای نسنجیده — دقیقاً همان
    # نوعِ سبزِ بی‌معنا که این بازنویسی برای برداشتنش است.
    if ! adb shell "run-as $PKG cat $PREFS" 2>/dev/null | grep -q 'logged_in'; then
        echo "✗ نوشتنِ حالتِ ورود شکست خورد — آزمون بی‌آنکه چیزی بسنجد سبز نمی‌ماند."
        return 1
    fi
}

# ───────────────────────────────────────────────────────────────────
# یک بار باز کردنِ اپ و سنجیدنش.
#   $1 = نامِ مرحله (برای لاگ)
# ───────────────────────────────────────────────────────────────────
#
# **چرا `am start` و نه `monkey`:** بارِ اول با `monkey` نوشته شده بود و
# خروجی‌اش هم دور ریخته می‌شد. وقتی مرحلهٔ داشبورد شکست، لاگ نمی‌توانست
# بگوید «اپ اصلاً باز نشد» یا «باز شد و مُرد» — و این دو تشخیصِ کاملاً
# متفاوت‌اند. `am start -W` صریح می‌گوید `Status: ok` یا `Error: …`.
#
# **چرا لاگِ خودِ اپ چاپ می‌شود، حتی وقتی همه‌چیز خوب است:** `tail -200`ِ
# لاگِ کامل روی شبیه‌سازِ CI پر است از پیامِ سرویس‌های گوگل و در پنجرهٔ
# ۲۰۰ خطی حتی یک خط از اپِ ما نبود. فیلترشده، همان ۲۰۰ خط همه‌اش
# به‌دردبخور است.
launch() {
    local label="$1"
    echo
    echo "═══ $label"

    adb shell am force-stop "$PKG" >/dev/null 2>&1
    adb logcat -c >/dev/null 2>&1 || true

    local started
    started=$(adb shell am start -W -n "$PKG/.MainActivity" 2>&1 | tr -d '\r')
    echo "$started" | sed 's/^/    /'
    if echo "$started" | grep -qi "Error"; then
        echo "✗ اپ اصلاً باز نشد — دستورِ راه‌اندازی خطا داد."
        return 1
    fi

    # به‌جای خوابِ ثابت، تا ۶۰ ثانیه صبر می‌کنیم ولی به محضِ کرش بیرون
    # می‌آییم. خوابِ ثابتِ ۲۵ ثانیه هم کند بودنِ شبیه‌ساز را تحمل نمی‌کرد
    # و هم وقتِ CI را سرِ حالت‌های سالم می‌سوزاند.
    local pid="" i=0
    while [ $i -lt 60 ]; do
        pid=$(adb shell pidof "$PKG" 2>/dev/null | tr -d '\r')
        [ -z "$pid" ] && [ $i -gt 3 ] && break
        adb logcat -d -b crash 2>/dev/null | grep -q "$PKG" && break
        i=$((i + 1))
        sleep 1
    done

    # همیشه چاپ می‌شود — چه سبز چه قرمز. سرنخِ «داشت چه می‌کرد که مُرد»
    # فقط همین‌جاست.
    echo "── لاگِ مربوط به اپ:"
    adb logcat -d 2>/dev/null | grep -Ei \
        "afghanjama|AndroidRuntime|FATAL|ANR in|lowmemorykiller|lmkd|Killing|native crash|DEBUG *:" \
        | tail -150 | sed 's/^/    /'

    local crash fatal anr
    crash=$(adb logcat -d -b crash 2>/dev/null | grep -A200 "$PKG" || true)
    fatal=$(adb logcat -d 2>/dev/null | grep -A80 "FATAL EXCEPTION" || true)
    anr=$(adb logcat -d 2>/dev/null | grep "ANR in $PKG" || true)

    # فقط کرشِ *این* اپ مهم است؛ سرویس‌های خودِ اندروید هم گاهی در
    # شبیه‌ساز می‌ترکند و آن ربطی به ما ندارد.
    if [ -n "$fatal" ] && ! echo "$fatal" | grep -q "$PKG"; then
        fatal=""
    fi

    if [ -n "$crash" ] || [ -n "$fatal" ] || [ -n "$anr" ]; then
        echo "════════════ اپ در «$label» کرش کرد ════════════"
        [ -n "$crash" ] && { echo "--- بافرِ crash ---"; echo "$crash"; }
        [ -n "$fatal" ] && { echo "--- FATAL EXCEPTION ---"; echo "$fatal"; }
        [ -n "$anr" ]   && { echo "--- ANR ---"; echo "$anr"; }
        return 1
    fi

    # نبودنِ کرش کافی نیست: اپ ممکن است بی‌صدا بسته شده باشد.
    pid=$(adb shell pidof "$PKG" 2>/dev/null | tr -d '\r')
    if [ -z "$pid" ]; then
        echo "✗ اپ زنده نیست و کرشی هم ثبت نشده — یعنی بی‌صدا بسته شد."
        echo "── چه چیزی روی صفحه است:"
        adb shell dumpsys activity activities 2>/dev/null \
            | grep -E "mResumedActivity|mFocusedApp" | sed 's/^/    /'
        return 1
    fi

    echo "── صفحهٔ روی نمایش:"
    adb shell dumpsys activity activities 2>/dev/null \
        | grep -E "mResumedActivity" | sed 's/^/    /'
    echo "✓ «$label» — اپ سرِ پا ماند (pid $pid)"
}

# ───────────────────────────────────────────────────────────────────
# مرحلهٔ ۱ — نصبِ تازه، بی هیچ حالتِ ذخیره‌شده.
# اپ باید روی صفحهٔ ورود بایستد. این همان چیزی است که نسخهٔ قبلی
# می‌سنجید و تنها چیزی است که تا امروز سنجیده می‌شد.
# ───────────────────────────────────────────────────────────────────
launch "۱/۴ نصبِ تازه (صفحهٔ ورود)" || exit 1

# ───────────────────────────────────────────────────────────────────
# مرحلهٔ ۲ — واردشده به عنوانِ فروش، یعنی مستقیم روی **داشبورد**.
#
# چرا نقشِ فروش و نه مدیر: مدیر بعد از ورود اول به صفحهٔ جملهٔ روز
# می‌رسد که هیچ دیتابیسی نمی‌خواند. نقشِ فروش یک‌راست به `HOME` می‌رود،
# جایی که `HomeDashboardScreen` و ViewModelهایش واقعاً از دیتابیس
# می‌خوانند. مدیر در مرحلهٔ ۴ جدا سنجیده می‌شود.
# ───────────────────────────────────────────────────────────────────
seed_auth SALES || exit 1
launch "۲/۴ واردشده — داشبورد" || exit 1

# سرِ پا بودن ثابت نمی‌کند که دیتابیس باز شده باشد. اگر `Room` بی‌صدا
# شکست بخورد و صفحه خالی بماند، اپ همچنان زنده است. وجودِ فایلِ دیتابیس
# تنها نشانهٔ محکمی است که از بیرونِ اپ می‌شود دید.
echo "── وارسیِ باز شدنِ دفتر (دیتابیس)"
if ! adb shell "run-as $PKG ls $DB" 2>/dev/null | grep -q 'afghanjama.db'; then
    echo "✗ فایلِ دیتابیس ساخته نشد — یعنی داشبورد به دفتر نرسیده است."
    adb logcat -d | tail -200
    exit 1
fi
echo "✓ دیتابیس ساخته و باز شد"

# ───────────────────────────────────────────────────────────────────
# مرحلهٔ ۳ — **بازِ دوم روی همان حالت.**
#
# این مهم‌ترین مرحله است. کرشی که روی گوشیِ کارگاه دیدیم روی نصبِ تازه
# رخ نمی‌داد؛ فقط وقتی می‌آمد که دیتابیس و تنظیمات از قبل وجود داشتند.
# اینجا اپ روی همان دیتابیسی که خودش ساخت دوباره باز می‌شود — نزدیک‌ترین
# چیزی که در CI به «گوشیِ پرِ کاربر» می‌شود ساخت.
# ───────────────────────────────────────────────────────────────────
launch "۳/۴ بازِ دوم روی دیتابیسِ موجود" || exit 1

# ───────────────────────────────────────────────────────────────────
# مرحلهٔ ۴ — نقشِ مدیر، مسیرِ دیگرِ بعد از ورود.
# ───────────────────────────────────────────────────────────────────
seed_auth MANAGER || exit 1
launch "۴/۴ واردشده به عنوانِ مدیر" || exit 1

echo
echo "✓✓ هر چهار حالت سالم بالا آمد."
